/// Looks up the policy for a command name, matching exact or stripped prefix.
pub fn find_policy(cmd_name: &str) -> Option<&'static CommandPolicy> {
    for policy in COMMAND_POLICY {
        if policy.name == cmd_name {
            return Some(policy);
        }
        if let Some(stripped) = policy.name.strip_prefix("cmd_")
            && stripped == cmd_name
        {
            return Some(policy);
        }
        if let Some(stripped) = cmd_name.strip_prefix("cmd_")
            && policy.name == stripped
        {
            return Some(policy);
        }
    }
    None
}
