#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Feature {
    Billing,
    Products,
    Customers,
    BasicReports,
    DayClose,
    Backup,
    ExportCsv,
    ExportXlsx,
    ExportWhatsapp,
    DiscoveryHub,
    SellGraph,
    Alerts,
    CustomReceipts,
    MultiCounter,
}

impl Feature {
    pub fn as_str(&self) -> &'static str {
        match self {
            Feature::Billing => "billing",
            Feature::Products => "products",
            Feature::Customers => "customers",
            Feature::BasicReports => "basic_reports",
            Feature::DayClose => "day_close",
            Feature::Backup => "backup",
            Feature::ExportCsv => "export_csv",
            Feature::ExportXlsx => "export_xlsx",
            Feature::ExportWhatsapp => "export_whatsapp",
            Feature::DiscoveryHub => "discovery_hub",
            Feature::SellGraph => "sell_graph",
            Feature::Alerts => "alerts",
            Feature::CustomReceipts => "custom_receipts",
            Feature::MultiCounter => "multi_counter",
        }
    }
}

/// Returns the feature set for the plan (`basic` or `pro`).
pub fn features_for(plan: &str) -> Vec<Feature> {
    match plan {
        "basic" => vec![
            Feature::Billing,
            Feature::Products,
            Feature::Customers,
            Feature::BasicReports,
            Feature::DayClose,
            Feature::Backup,
            Feature::ExportCsv,
        ],
        "pro" => vec![
            Feature::Billing,
            Feature::Products,
            Feature::Customers,
            Feature::BasicReports,
            Feature::DayClose,
            Feature::Backup,
            Feature::ExportCsv,
            Feature::ExportXlsx,
            Feature::ExportWhatsapp,
            Feature::DiscoveryHub,
            Feature::SellGraph,
            Feature::Alerts,
            Feature::CustomReceipts,
            Feature::MultiCounter,
        ],
        _ => Vec::new(),
    }
}

