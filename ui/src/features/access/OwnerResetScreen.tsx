import React, { useState } from 'react';
import { apiOwnerResetWithCode } from './clientApi';

interface OwnerResetScreenProps {
  onBackToLogin: () => void;
  onResetSuccess: () => void;
}

export const OwnerResetScreen: React.FC<OwnerResetScreenProps> = ({
  onBackToLogin,
  onResetSuccess,
}) => {
  const [resetCode, setResetCode] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [successMessage, setSuccessMessage] = useState<string | null>(null);

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setError(null);
    setLoading(true);

    try {
      const res = await apiOwnerResetWithCode(resetCode);
      if (!res.success) {
        throw new Error(res.message || 'Owner reset rejected by control plane.');
      }
      setSuccessMessage(
        res.message ||
          'Owner reset verified! The primary owner account has been updated with your temporary password. Please sign in now to set your permanent password.'
      );
    } catch (err: any) {
      setError(err.message || 'Invalid or expired vendor reset code.');
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="min-h-screen bg-slate-950 flex flex-col justify-center py-12 sm:px-6 lg:px-8">
      <div className="sm:mx-auto sm:w-full sm:max-w-md">
        <div className="flex items-center justify-center gap-2.5 mb-6">
          <div className="w-10 h-10 rounded-xl bg-indigo-600 flex items-center justify-center font-bold text-white shadow-lg shadow-indigo-500/20 text-lg">
            OB
          </div>
          <span className="font-bold text-2xl text-white tracking-tight">OmniBill ERP</span>
        </div>

        <div className="bg-slate-900 py-8 px-6 shadow-2xl rounded-2xl sm:px-10 border border-slate-800">
          <div className="mb-6">
            <h2 className="text-xl font-bold text-white tracking-tight">Reset Owner Password</h2>
            <p className="text-xs text-slate-400 mt-1">
              Enter the temporary reset code generated by your vendor control plane admin.
            </p>
          </div>

          {successMessage ? (
            <div className="space-y-6 text-center">
              <div className="w-14 h-14 bg-emerald-500/10 border border-emerald-500/30 rounded-full flex items-center justify-center mx-auto text-emerald-400">
                <svg className="w-7 h-7" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                  <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M5 13l4 4L19 7" />
                </svg>
              </div>
              <p className="text-xs text-emerald-300 bg-emerald-950/40 border border-emerald-800/40 p-3 rounded-lg leading-relaxed">
                {successMessage}
              </p>
              <button
                onClick={onResetSuccess}
                className="w-full py-3 px-4 bg-emerald-600 hover:bg-emerald-500 text-white rounded-xl font-semibold shadow-lg shadow-emerald-600/20 transition-all text-sm"
              >
                Sign In with Reset Password
              </button>
            </div>
          ) : (
            <form onSubmit={handleSubmit} className="space-y-4">
              <div>
                <label className="block text-xs font-semibold text-slate-300 uppercase tracking-wider mb-1.5">
                  Vendor Temporary Reset Code
                </label>
                <input
                  type="text"
                  required
                  autoFocus
                  placeholder="Enter reset code"
                  value={resetCode}
                  onChange={(e) => setResetCode(e.target.value)}
                  className="w-full px-3.5 py-2.5 bg-slate-950 border border-slate-700 rounded-xl text-white text-sm focus:outline-none focus:border-indigo-500 font-mono tracking-wider text-center"
                />
              </div>

              {error && (
                <div className="text-xs text-rose-300 bg-rose-950/60 p-3 rounded-lg border border-rose-800">
                  {error}
                </div>
              )}

              <div className="pt-2">
                <button
                  type="submit"
                  disabled={loading || !resetCode.trim()}
                  className="w-full py-3 px-4 bg-indigo-600 hover:bg-indigo-500 text-white rounded-xl font-semibold shadow-lg shadow-indigo-600/20 transition-all text-sm disabled:opacity-50"
                >
                  {loading ? 'Verifying Code...' : 'Verify & Reset Access'}
                </button>
              </div>

              <div className="mt-4 text-center">
                <button
                  type="button"
                  onClick={onBackToLogin}
                  className="text-xs text-slate-400 hover:text-slate-200 transition-colors"
                >
                  ← Back to Sign In
                </button>
              </div>
            </form>
          )}
        </div>
      </div>
    </div>
  );
};
